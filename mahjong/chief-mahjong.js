  /* ---------------------------------- theme validation ---------------------------------- */
  function themeError(theme, msg) {
    var id = isObj(theme) && typeof theme.id === 'string' ? theme.id : '?';
    return new Error('ChiefMahjong theme "' + id + '": ' + msg);
  }
  function validateTheme(theme) {
    if (typeof theme === 'string') {
      if (!hasOwn(BUILTIN_THEMES, theme)) throw new Error('ChiefMahjong: unknown theme "' + theme + '" (builtin: ' + Object.keys(BUILTIN_THEMES).join(', ') + ')');
      theme = BUILTIN_THEMES[theme];
    }
    if (!isObj(theme)) throw new Error('ChiefMahjong theme: must be an object or a builtin name');
    var k;
    for (k in theme) if (hasOwn(theme, k) && THEME_KEYS.indexOf(k) < 0) throw themeError(theme, 'unknown key "' + k + '"');
    if (typeof theme.id !== 'string' || !/^[a-z0-9_-]{1,40}$/.test(theme.id)) throw themeError(theme, 'id must be 1-40 [a-z0-9_-]');
    if (!isObj(theme.name) || typeof theme.name.en !== 'string' || !theme.name.en) throw themeError(theme, 'name.en is required');
    if (!isObj(theme.tiles)) throw themeError(theme, 'tiles must be an object {kind-id: {icon, colorToken, rotate?, index?}}');
    for (k in theme.tiles) if (hasOwn(theme.tiles, k) && !hasOwn(KIND_BY_ID, k)) throw themeError(theme, 'tiles.' + k + ' is not a kind');
    for (var i = 0; i < BUILTIN_KINDS.length; i++) {
      var kid = BUILTIN_KINDS[i].id, t = theme.tiles[kid];
      if (!hasOwn(theme.tiles, kid)) throw themeError(theme, 'tiles.' + kid + ' is missing (a theme covers all ' + BUILTIN_KINDS.length + ' kinds)');
      if (!isObj(t)) throw themeError(theme, 'tiles.' + kid + ' must be an object');
      for (k in t) if (hasOwn(t, k) && TILE_KEYS.indexOf(k) < 0) throw themeError(theme, 'tiles.' + kid + ': unknown key "' + k + '"');
      if (typeof t.icon !== 'string' || !hasOwn(ICONS, t.icon)) throw themeError(theme, 'tiles.' + kid + '.icon "' + t.icon + '" is not in ChiefMahjong.ICONS');
      if (typeof t.colorToken !== 'string' || !TOKEN_RE.test(t.colorToken)) throw themeError(theme, 'tiles.' + kid + '.colorToken must be a --chief-* token');
      if (t.rotate !== undefined && ROTATIONS.indexOf(t.rotate) < 0) throw themeError(theme, 'tiles.' + kid + '.rotate must be 0, 90, 180 or 270');
      if (t.index !== undefined && typeof t.index !== 'boolean') throw themeError(theme, 'tiles.' + kid + '.index must be true or false');
    }
    return theme;
  }

  /* ---------------------------------- rendering ---------------------------------- */
  function normalizeOpts(opts) {
    var o = {}, k;
    for (k in DEFAULTS) o[k] = DEFAULTS[k];
    if (opts) for (k in opts) if (opts[k] !== undefined && opts[k] !== null) o[k] = opts[k];
    o.size = +o.size; o.radius = +o.radius;
    if (!(o.size > 0)) throw new Error('ChiefMahjong.render: opts.size must be a positive number');
    if (!(o.radius >= 0)) throw new Error('ChiefMahjong.render: opts.radius must be >= 0');
    o.selected = !!o.selected; o.blocked = !!o.blocked; o.hint = !!o.hint; o.edge = o.edge !== false;
    return o;
  }

  /* geometry(opts): pixel sizes for the game UI (it only positions; the depth side is part of the SVG). */
  function geometry(opts) {
    var o = normalizeOpts(opts), s = o.size / FW;
    var e = o.edge ? EDGE : 0;
    return { faceWidth: n(o.size), faceHeight: n(FH * s), edge: n(e * s), width: n((FW + e) * s), height: n((FH + e) * s) };
  }

  function iconSVG(spec, cx, cy, size, rot, colorTok, faceTok) {
    var t = 'translate(' + n(cx - size / 2) + ' ' + n(cy - size / 2) + ') scale(' + n(size / 100) + ')';
    if (rot) t += ' rotate(' + rot + ' 50 50)';
    var out = '<g transform="' + t + '">';
    for (var i = 0; i < spec.paths.length; i++) {
      var p = spec.paths[i];
      if (!(typeof p.d === 'string' && p.d.length > 0 && p.d.length < 8000 && PATH_RE.test(p.d))) {
        throw new Error('ChiefMahjong: invalid icon path');
      }
      var tok = p.colorToken === FACE_REF ? faceTok : (p.colorToken || colorTok);
      out += '<path d="' + p.d + '"' + (p.fillRule === 'evenodd' ? ' fill-rule="evenodd"' : '') + ' style="' + fill(tok) + '"/>';
    }
    return out + '</g>';
  }

  function tileLabel(kind) {
    if (WIND_LABEL[kind.id]) return WIND_LABEL[kind.id];
    var base = CATEGORY_LABEL[kind.category] || 'Tile';
    if (kind.rank) return base + ', ' + kind.rank;
    return base + ' ' + kind.id.slice(kind.id.indexOf('-') + 1);
  }

  function render(tile, opts) {
    if (!isObj(tile)) throw new Error('ChiefMahjong.render: tile must be an object {kind, id?}');
    if (typeof tile.kind !== 'string' || !hasOwn(KIND_BY_ID, tile.kind)) throw new Error('ChiefMahjong.render: unknown kind "' + tile.kind + '"');
    var o = normalizeOpts(opts);
    var theme = validateTheme(o.theme);
    var kind = KIND_BY_ID[tile.kind], spec = theme.tiles[kind.id];
    var e = o.edge ? EDGE : 0, s = o.size / FW;
    var rx = Math.min(o.radius / s, 20);
    var faceTok = o.blocked ? '--chief-bg' : '--chief-surface-2';
    var lineTok = o.selected ? '--chief-accent' : (o.hint ? '--chief-ok' : (o.blocked ? '--chief-border' : '--chief-border-strong'));
    var lineW = (o.selected || o.hint) ? 6 : 2;
    var inner = '';
    if (e) inner += '<path d="' + rr(e, e, FW, FH, rx) + '" style="' + fill(o.blocked ? '--chief-surface' : '--chief-border') + '"/>';
    var half = lineW / 2;
    inner += '<path d="' + rr(half, half, FW - lineW, FH - lineW, Math.max(rx - half, 0)) + '" style="' + fill(faceTok) +
      ';stroke:var(' + lineTok + ');stroke-width:' + lineW + '"/>';
    var layout = kind.rank ? PIP_LAYOUTS[kind.rank] : HONOUR;
    var icon = ICONS[spec.icon];
    for (var i = 0; i < layout.at.length; i++) {
      inner += iconSVG(icon, layout.at[i][0], layout.at[i][1], layout.size, spec.rotate || 0, spec.colorToken, faceTok);
    }
    var showIndex = spec.index === undefined ? !!kind.rank : spec.index;
    if (showIndex && kind.rank) {
      inner += '<text x="8" y="19" style="' + fill(spec.colorToken) + ';font-family:var(--chief-font-body);font-weight:700;font-size:16px">' +
        kind.rank + '</text>';
    }
    return '<svg xmlns="http://www.w3.org/2000/svg" class="cm-svg" viewBox="0 0 ' + (FW + e) + ' ' + (FH + e) + '" width="' +
      n((FW + e) * s) + '" height="' + n((FH + e) * s) + '" role="img" aria-label="' + esc(tileLabel(kind)) + '" data-kind="' +
      esc(kind.id) + '"' + (tile.id !== undefined && tile.id !== null ? ' data-tile-id="' + esc(tile.id) + '"' : '') + '>' +
      inner + '</svg>';
  }

  function kind(id) { return hasOwn(KIND_BY_ID, id) ? KIND_BY_ID[id] : null; }
  function matches(a, b) {                          // same group = a pair (flowers/seasons: any two of their group)
    var ka = kind(a), kb = kind(b);
    return !!(ka && kb && ka.group === kb.group);
  }

  /* ------------------------- mount: CSP-safe DOM insert ------------------------- */
  /* Deliberate copy of ChiefCards.splitStyles/mount (stand-alone library, ChiefCards stays untouched): render() colours
     via style="fill:var(--chief-…)", which a strict CSP (style-src 'self') blocks in markup and in DOMParser.
     splitStyles() moves every style="…" to data-cm-s="<index>" + a list; mount() parses that markup (DOMParser +
     importNode, never innerHTML) and applies the declarations via CSSOM (el.style.setProperty). */
  var STYLE_ATTR_RE = / style="([^"]*)"/g, STASH_ATTR = 'data-cm-s';
  function splitStyles(svg) {
    if (typeof svg !== 'string' || svg.indexOf('<svg') !== 0) throw new Error('ChiefMahjong.splitStyles: expects an SVG string from render()');
    var styles = [];
    var markup = svg.replace(STYLE_ATTR_RE, function (_m, css) {
      styles.push(css);
      return ' ' + STASH_ATTR + '="' + (styles.length - 1) + '"';
    });
    return { markup: markup, styles: styles };
  }
  function applyDecls(el, css) {
    var parts = String(css).split(';');
    for (var i = 0; i < parts.length; i++) {
      var k = parts[i].indexOf(':');
      if (k > 0) el.style.setProperty(parts[i].slice(0, k).trim(), parts[i].slice(k + 1).trim());
    }
  }
  function mount(el, svg) {
    if (!el || el.nodeType !== 1) throw new Error('ChiefMahjong.mount: el must be a DOM element');
    var parts = splitStyles(svg);
    var doc = el.ownerDocument;
    var Parser = (doc.defaultView && doc.defaultView.DOMParser) || root.DOMParser;
    var parsed = new Parser().parseFromString(parts.markup, 'image/svg+xml').documentElement;
    if (!parsed || parsed.nodeName.toLowerCase() !== 'svg' || parsed.getElementsByTagName('parsererror').length) {
      throw new Error('ChiefMahjong.mount: markup is not a valid SVG');
    }
    var node = doc.importNode(parsed, true);
    var marked = [node].concat(Array.prototype.slice.call(node.querySelectorAll('[' + STASH_ATTR + ']')));
    for (var i = 0; i < marked.length; i++) {
      if (!marked[i].hasAttribute(STASH_ATTR)) continue;
      var idx = +marked[i].getAttribute(STASH_ATTR);
      marked[i].removeAttribute(STASH_ATTR);
      if (idx >= 0 && idx < parts.styles.length) applyDecls(marked[i], parts.styles[idx]);
    }
    while (el.firstChild) el.removeChild(el.firstChild);
    el.appendChild(node);
    return node;
  }

