  function iconSpecFor(card) {
    var m = card.meta || {};
    if (typeof m.icon === 'string') {
      if (!hasOwn(ICONS, m.icon)) throw new Error('ChiefCards.render: card ' + card.id + ': unknown icon "' + m.icon + '" (known: ' + Object.keys(ICONS).join(', ') + ')');
      var reg = ICONS[m.icon];
      return { paths: reg.paths, rotate: (reg.rotate || 0) + (+m.iconRotate || 0) };
    }
    if (isObj(m.icon) && Array.isArray(m.icon.paths) && m.icon.paths.length) {
      var paths = [];
      for (var i = 0; i < m.icon.paths.length; i++) {
        var p = m.icon.paths[i];
        if (!isObj(p) || !validPath(p.d)) throw new Error('ChiefCards.render: card ' + card.id + ': meta.icon.paths[' + i + '].d is not a valid SVG path');
        paths.push({ d: p.d, fillRule: p.fillRule, stroke: typeof p.stroke === 'number' ? p.stroke : 0, colorToken: p.colorToken });
      }
      return { paths: paths, rotate: +m.icon.rotate || +m.iconRotate || 0 };
    }
    if (m.iconPath !== undefined) {
      if (!validPath(m.iconPath)) throw new Error('ChiefCards.render: card ' + card.id + ': meta.iconPath is not a valid SVG path');
      return { paths: [{ d: m.iconPath, fillRule: m.iconFillRule }], rotate: +m.iconRotate || 0 };
    }
    if (SUIT_PATHS[card.suit]) return { paths: [{ d: SUIT_PATHS[card.suit] }], rotate: 0 };
    return null;
  }

