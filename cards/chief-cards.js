  /* ---------------------------------- render ---------------------------------- */
  function normalizeOpts(opts) {
    var o = {}, k;
    for (k in DEFAULTS) o[k] = DEFAULTS[k];
    if (opts) for (k in opts) if (opts[k] !== undefined && opts[k] !== null) o[k] = opts[k];
    o.size = +o.size; o.radius = +o.radius;
    if (!(o.size > 0)) throw new Error('ChiefCards.render: opts.size must be a positive number');
    if (!(o.radius >= 0)) throw new Error('ChiefCards.render: opts.radius must be >= 0');
    if (FACE_STYLES.indexOf(o.faceStyle) < 0) throw new Error('ChiefCards.render: opts.faceStyle must be one of ' + FACE_STYLES.join(', '));
    if (BACK_STYLES.indexOf(o.backStyle) < 0) throw new Error('ChiefCards.render: opts.backStyle must be one of ' + BACK_STYLES.join(', '));
    o.faceDown = !!o.faceDown;
    return o;
  }

  function cardLabel(card) {
    if (card.rank === 'JOKER') return 'Joker';
    if (card.suit === 'custom') return 'Custom card ' + ((card.meta && (card.meta.title || card.meta.label)) || card.rank);
    return (RANK_NAMES[card.rank] || card.rank) + ' of ' + card.suit;
  }

  function render(card, opts) {
    if (!isObj(card)) throw new Error('ChiefCards.render: card must be an object {id, suit, rank, meta}');
    if (typeof card.rank !== 'string' || !card.rank) throw new Error('ChiefCards.render: card.rank must be a non-empty string');
    var o = normalizeOpts(opts);
    var rx = Math.min(o.radius * W / o.size, 40);
    var m = isObj(card.meta) ? card.meta : {};
    var inner, aria;

    if (o.faceDown) {
      inner = backFace(o, rx);
      aria = 'Card, face down';
    } else {
      var faceTok = tok(m.faceToken, '--chief-card-face');
      var edgeTok = faceTok === '--chief-card-face' ? '--chief-print-rule' : '--chief-border-strong';
      inner = body(faceTok, rx, edgeTok);
      aria = cardLabel(card);
      if (card.rank === 'JOKER') {
        inner += jokerFace(card);
      } else {
        var spec = iconSpecFor(card);
        var ink = inkFor(card);
        if (card.suit === 'custom') {
          var iconTok = tok(m.iconColorToken, ink);
          inner += corners(m.label === undefined ? card.rank : m.label, spec, ink, iconTok, faceTok) + customFace(card, spec, ink, iconTok, faceTok);
        } else {
          if (!spec) throw new Error('ChiefCards.render: card ' + card.id + ': unknown suit "' + card.suit + '" (use ' + SUITS.join('/') + ', "custom", or meta.icon/iconPath)');
          var label = m.label === undefined ? card.rank : m.label;
          inner += corners(label, spec, ink, ink, faceTok);
          if (card.rank === 'J' || card.rank === 'Q' || card.rank === 'K') {
            inner += o.faceStyle === 'monogram' ? courtMonogram(card, spec, ink) : courtMinimal(card, spec, ink);
          } else if (card.rank === 'A' || LAYOUTS[card.rank]) {
            inner += pipsFace(card, spec, ink);
          } else {
            inner += customFace(card, spec, ink, ink, faceTok);
          }
        }
      }
    }
    return '<svg xmlns="http://www.w3.org/2000/svg" class="cc-svg" viewBox="0 0 ' + W + ' ' + H + '" width="' + n(o.size) +
      '" height="' + n(o.size * H / W) + '" role="img" aria-label="' + esc(aria) + '"' +
      (card.id !== undefined ? ' data-card-id="' + esc(card.id) + '"' : '') + '>' + inner + '</svg>';
  }

  /* flip widget: <button class="cc-card"> with front + back; pair with bindFlip() and chief-cards.css */
  function flipHTML(card, opts) {
    var o = normalizeOpts(opts);
    var front = render(card, mergeOpts(o, { faceDown: false }));
    var back = render(card, mergeOpts(o, { faceDown: true }));
    return '<button type="button" class="cc-card' + (o.faceDown ? ' is-flipped' : '') + '" data-flip aria-pressed="' + o.faceDown +
      '" aria-label="' + esc(cardLabel(card)) + ', flip" style="--cc-w:' + n(o.size) + 'px;--cc-radius:' + n(o.radius) + 'px">' +
      '<span class="cc-card-inner"><span class="cc-face cc-front">' + front + '</span><span class="cc-face cc-back">' + back +
      '</span></span></button>';
  }
  function mergeOpts(a, b) { var o = {}, k; for (k in a) o[k] = a[k]; for (k in b) o[k] = b[k]; return o; }

  function bindFlip(el) {
    function onClick(ev) {
      var btn = ev.target && ev.target.closest ? ev.target.closest('.cc-card[data-flip]') : null;
      if (!btn || !el.contains(btn)) return;
      var flipped = btn.classList.toggle('is-flipped');
      btn.setAttribute('aria-pressed', String(flipped));
    }
    el.addEventListener('click', onClick);
    return function () { el.removeEventListener('click', onClick); };
  }

  /* ---------------------------------- decks ---------------------------------- */
  var DECK_KEYS = ['name', 'description', 'suits', 'ranks', 'copies', 'extra_cards', 'custom_cards', 'templates'];
  var META_KEYS = ['label', 'title', 'colorToken', 'iconColorToken', 'faceToken', 'icon', 'iconPath', 'iconFillRule', 'iconRotate', 'variant'];
  var TOKEN_FIELDS = ['colorToken', 'iconColorToken', 'faceToken'];
  var MAX = { label: 12, title: 24, rank: 6, count: 200 };

  function deckErr(name, msg) { return new Error('ChiefCards deck "' + name + '": ' + msg); }

  /* validates one meta object; `fail(msg)` throws with the deck name; returns a deep copy */
  function validateMeta(meta, where, fail) {
    if (meta === undefined) return {};
    if (!isObj(meta)) fail(where + ' must be an object');
    var out = {}, k;
    for (k in meta) {
      var v = meta[k], at = where + '.' + k;
      if (META_KEYS.indexOf(k) < 0) fail(at + ': unknown key (allowed: ' + META_KEYS.join(', ') + ')');
      if (k === 'label' || k === 'title') {
        if (typeof v !== 'string') fail(at + ' must be a string');
        if (displayLen(v) > MAX[k]) fail(at + ' is too long (max ' + MAX[k] + ' chars)');
      } else if (TOKEN_FIELDS.indexOf(k) >= 0) {
        if (typeof v !== 'string' || !CHIEF_TOKEN_RE.test(v)) fail(at + ' = ' + JSON.stringify(v) + ' is not a valid token (must start with "--chief-")');
      } else if (k === 'icon') {
        if (typeof v === 'string') {
          if (!hasOwn(ICONS, v)) fail(at + ' = ' + JSON.stringify(v) + ' is not a known icon (known: ' + Object.keys(ICONS).join(', ') + ')');
        } else if (isObj(v)) {
          for (var ik in v) if (ik !== 'paths' && ik !== 'rotate') fail(at + '.' + ik + ': unknown key (allowed: paths, rotate)');
          if (!Array.isArray(v.paths) || !v.paths.length) fail(at + '.paths must be a non-empty array');
          if (v.rotate !== undefined && (typeof v.rotate !== 'number' || !isFinite(v.rotate))) fail(at + '.rotate must be a number');
          for (var pi = 0; pi < v.paths.length; pi++) {
            var p = v.paths[pi], pat = at + '.paths[' + pi + ']';
            if (!isObj(p)) fail(pat + ' must be an object {d, stroke?, fillRule?, colorToken?}');
            for (var pk in p) if (['d', 'stroke', 'fillRule', 'colorToken'].indexOf(pk) < 0) fail(pat + '.' + pk + ': unknown key');
            if (!validPath(p.d)) fail(pat + '.d is not a valid SVG path');
            if (p.stroke !== undefined && !(typeof p.stroke === 'number' && p.stroke > 0)) fail(pat + '.stroke must be a number > 0');
            if (p.fillRule !== undefined && p.fillRule !== 'evenodd' && p.fillRule !== 'nonzero') fail(pat + '.fillRule must be "evenodd" or "nonzero"');
            if (p.colorToken !== undefined && p.colorToken !== FACE_REF && !CHIEF_TOKEN_RE.test(p.colorToken)) {
              fail(pat + '.colorToken = ' + JSON.stringify(p.colorToken) + ' is not a valid token (must start with "--chief-", or "@face")');
            }
          }
        } else {
          fail(at + ' must be an icon name or {paths: [...]}');
        }
      } else if (k === 'iconPath') {
        if (!validPath(v)) fail(at + ' is not a valid SVG path');
      } else if (k === 'iconFillRule') {
        if (v !== 'evenodd' && v !== 'nonzero') fail(at + ' must be "evenodd" or "nonzero"');
      } else if (k === 'iconRotate') {
        if (typeof v !== 'number' || !isFinite(v)) fail(at + ' must be a number');
      } else if (k === 'variant') {
        if (v !== 'accent' && v !== 'ink') fail(at + ' must be "accent" or "ink"');
      }
      out[k] = (v && typeof v === 'object') ? clone(v) : v;
    }
    if (out.icon !== undefined && out.iconPath !== undefined) fail(where + ': use either icon or iconPath, not both');
    return out;
  }

  function checkRank(v, at, fail) {
    if (typeof v !== 'string' || !v || displayLen(v) > MAX.rank) fail(at + ' must be a 1-' + MAX.rank + ' char string');
  }

  /* full validation → normalized deck; throws Error('ChiefCards deck "<name>": <path> …') */
  function validateDeck(input) {
    var d = input, name = '?', i, k;
    if (typeof input === 'string') {
      try { d = JSON.parse(input); } catch (e) { throw deckErr(name, 'invalid JSON (' + e.message + ')'); }
    }
    if (!isObj(d)) throw deckErr(name, 'deck must be a JSON object');
    if (typeof d.name !== 'string' || !ID_RE.test(d.name)) throw deckErr(name, '"name" must be 1-40 chars [a-z0-9_-]');
    name = d.name;
    var fail = function (msg) { throw deckErr(name, msg); };
    for (k in d) if (DECK_KEYS.indexOf(k) < 0) fail('unknown key "' + k + '" (allowed: ' + DECK_KEYS.join(', ') + ')');
    if (d.description !== undefined && typeof d.description !== 'string') fail('"description" must be a string');

    function list(key, allowed) {
      var arr = d[key] === undefined ? [] : d[key];
      if (!Array.isArray(arr)) fail('"' + key + '" must be an array (may be empty)');
      var seen = {};
      for (var j = 0; j < arr.length; j++) {
        if (allowed.indexOf(arr[j]) < 0) fail(key + '[' + j + '] = ' + JSON.stringify(arr[j]) + ' is not valid (allowed: ' + allowed.join(', ') + ')');
        if (seen[arr[j]]) fail(key + '[' + j + '] = ' + JSON.stringify(arr[j]) + ' is a duplicate');
        seen[arr[j]] = true;
      }
      return arr.slice();
    }
    var suits = list('suits', SUITS);
    var ranks = list('ranks', RANKS);
    if (!suits.length !== !ranks.length) fail('"suits" and "ranks" must both be non-empty, or both empty (fully custom deck)');
    var copies = d.copies === undefined ? 1 : d.copies;
    if (typeof copies !== 'number' || copies % 1 !== 0 || copies < 1 || copies > 8) fail('"copies" must be an integer 1-8');

    /* extra_cards: single cards (jokers, an extra standard card, a one-off custom) */
    var extrasIn = d.extra_cards === undefined ? [] : d.extra_cards;
    if (!Array.isArray(extrasIn)) fail('"extra_cards" must be an array');
    var extras = [];
    for (i = 0; i < extrasIn.length; i++) {
      var x = extrasIn[i], where = 'extra_cards[' + i + ']', suit;
      if (!isObj(x)) fail(where + ' must be an object {rank, suit?, meta?}');
      for (k in x) if (['rank', 'suit', 'meta'].indexOf(k) < 0) fail(where + ': unknown key "' + k + '"');
      if (x.rank === 'JOKER') {
        if (x.suit !== undefined) fail(where + ': a JOKER has no suit');
        suit = 'joker';
      } else if (x.suit === 'custom') {
        checkRank(x.rank, where + '.rank', fail);
        suit = 'custom';
      } else {
        if (RANKS.indexOf(x.rank) < 0) fail(where + ': rank ' + JSON.stringify(x.rank) + ' is not valid (JOKER, ' + RANKS.join(', ') + ', or suit "custom")');
        if (SUITS.indexOf(x.suit) < 0) fail(where + ': suit ' + JSON.stringify(x.suit) + ' is not valid (' + SUITS.join(', ') + ', custom)');
        suit = x.suit;
      }
      extras.push({ rank: x.rank, suit: suit, meta: validateMeta(x.meta, where + '.meta', fail) });
    }

    /* custom_cards: N copies of a custom card with ids <id_prefix>-1 … -N */
    var customIn = d.custom_cards === undefined ? [] : d.custom_cards;
    if (!Array.isArray(customIn)) fail('"custom_cards" must be an array');
    var customs = [], prefixes = {};
    for (i = 0; i < customIn.length; i++) {
      var cc = customIn[i], cw = 'custom_cards[' + i + ']';
      if (!isObj(cc)) fail(cw + ' must be an object {id_prefix, rank, count, meta?}');
      for (k in cc) if (['id_prefix', 'rank', 'count', 'meta'].indexOf(k) < 0) fail(cw + ': unknown key "' + k + '" (allowed: id_prefix, rank, count, meta)');
      ['id_prefix', 'rank', 'count'].forEach(function (f) { if (cc[f] === undefined) fail(cw + ': missing field "' + f + '"'); });
      if (typeof cc.id_prefix !== 'string' || !ID_RE.test(cc.id_prefix)) fail(cw + '.id_prefix must be 1-40 chars [a-z0-9_-]');
      if (prefixes[cc.id_prefix]) fail(cw + '.id_prefix = ' + JSON.stringify(cc.id_prefix) + ' is a duplicate (also ' + prefixes[cc.id_prefix] + ')');
      prefixes[cc.id_prefix] = cw;
      checkRank(cc.rank, cw + '.rank', fail);
      if (typeof cc.count !== 'number' || cc.count % 1 !== 0 || cc.count < 1 || cc.count > MAX.count) fail(cw + '.count must be an integer 1-' + MAX.count);
      customs.push({ id_prefix: cc.id_prefix, rank: cc.rank, count: cc.count, meta: validateMeta(cc.meta, cw + '.meta', fail) });
    }

    /* templates: cards the game creates at runtime via fromTemplate(); {var} placeholders in rank/label/title */
    var tplIn = d.templates === undefined ? {} : d.templates;
    if (!isObj(tplIn)) fail('"templates" must be an object {name: {rank, meta}}');
    var templates = {};
    for (k in tplIn) {
      var t = tplIn[k], tw = 'templates.' + k;
      if (!ID_RE.test(k)) fail(tw + ': template name must be 1-40 chars [a-z0-9_-]');
      if (!isObj(t)) fail(tw + ' must be an object {rank, meta?}');
      for (var tk in t) if (tk !== 'rank' && tk !== 'meta') fail(tw + ': unknown key "' + tk + '" (allowed: rank, meta)');
      if (t.rank === undefined) fail(tw + ': missing field "rank"');
      if (typeof t.rank !== 'string' || !t.rank) fail(tw + '.rank must be a non-empty string');
      templates[k] = { rank: t.rank, meta: validateMeta(t.meta, tw + '.meta', fail) };
    }

    var total = suits.length * ranks.length * copies + extras.length;
    for (i = 0; i < customs.length; i++) total += customs[i].count;
    if (total < 1) fail('deck has no cards (add suits + ranks, extra_cards or custom_cards)');

    return { name: name, description: d.description || '', suits: suits, ranks: ranks, copies: copies,
      extras: extras, customs: customs, templates: templates, total: total };
  }

  function loadDeck(input) {
    var v = validateDeck(input), name = v.name, cards = [], c, s, r, i;
    for (c = 1; c <= v.copies; c++) {
      for (s = 0; s < v.suits.length; s++) {
        for (r = 0; r < v.ranks.length; r++) {
          cards.push({ id: name + '-' + v.suits[s] + '-' + v.ranks[r] + (v.copies > 1 ? '-c' + c : ''), suit: v.suits[s], rank: v.ranks[r], meta: {} });
        }
      }
    }
    for (i = 0; i < v.extras.length; i++) {
      var x = v.extras[i];
      cards.push({ id: name + '-' + x.suit + '-' + String(x.rank).toLowerCase().replace(/[^a-z0-9]+/g, '') + '-x' + (i + 1), suit: x.suit, rank: x.rank, meta: clone(x.meta) });
    }
    for (i = 0; i < v.customs.length; i++) {
      var cc = v.customs[i];
      for (c = 1; c <= cc.count; c++) cards.push({ id: cc.id_prefix + '-' + c, suit: 'custom', rank: cc.rank, meta: clone(cc.meta) });
    }
    var seen = {};
    for (i = 0; i < cards.length; i++) {
      if (seen[cards[i].id]) throw deckErr(name, 'duplicate card id "' + cards[i].id + '" (pick another id_prefix)');
      seen[cards[i].id] = true;
    }
    return cards;
  }

  /* ---------------------------------- templates ---------------------------------- */
  var templateSeq = 0;

  /* deck = deck JSON (object/string) or a BUILTIN_DECKS name; vars fill {placeholders} (HTML/XML-escaped) */
  function fromTemplate(deck, templateName, vars) {
    var src = deck;
    if (typeof deck === 'string' && hasOwn(BUILTIN_DECKS, deck)) src = BUILTIN_DECKS[deck];
    var v = validateDeck(src);
    var where = 'ChiefCards.fromTemplate: deck "' + v.name + '", template "' + templateName + '": ';
    if (!hasOwn(v.templates, templateName)) {
      throw new Error(where + 'unknown template (known: ' + (Object.keys(v.templates).join(', ') || 'none') + ')');
    }
    var t = v.templates[templateName];
    vars = vars || {};
    if (!isObj(vars)) throw new Error(where + 'vars must be an object');
    function fillIn(str, field) {
      var out = str.replace(PLACEHOLDER_RE, function (_, key) {
        if (!hasOwn(vars, key) || vars[key] === undefined || vars[key] === null) throw new Error(where + 'missing variable "' + key + '" (in ' + field + ')');
        var val = vars[key];
        if (typeof val !== 'string' && !(typeof val === 'number' && isFinite(val))) throw new Error(where + 'variable "' + key + '" must be a string or number');
        return esc(String(val));
      });
      var max = field === 'rank' ? MAX.rank : MAX[field];
      if (displayLen(out) > max) throw new Error(where + field + ' "' + out + '" is too long after filling in (max ' + max + ' chars)');
      return out;
    }
    var meta = clone(t.meta);
    if (typeof meta.label === 'string') meta.label = fillIn(meta.label, 'label');
    if (typeof meta.title === 'string') meta.title = fillIn(meta.title, 'title');
    var rank = fillIn(t.rank, 'rank');
    meta.template = templateName;
    templateSeq += 1;
    return { id: v.name + '-' + templateName + '-' + templateSeq + '-' + randomInt(2147483647).toString(36), suit: 'custom', rank: rank, meta: meta };
  }

  /* ---------------------------------- shuffle ---------------------------------- */
  function getCrypto() {
    var c = (root && root.crypto) || (typeof crypto !== 'undefined' ? crypto : null);
    if (!c || typeof c.getRandomValues !== 'function') throw new Error('ChiefCards: crypto.getRandomValues is not available');
    return c;
  }
  /* unbiased int in [0, max) via rejection sampling */
  function randomInt(max) {
    var c = getCrypto(), buf = new Uint32Array(1), limit = Math.floor(4294967296 / max) * max;
    do { c.getRandomValues(buf); } while (buf[0] >= limit);
    return buf[0] % max;
  }
  /* Fisher-Yates; returns a NEW array, input untouched */
  function shuffle(arr) {
    if (!Array.isArray(arr)) throw new Error('ChiefCards.shuffle: expects an array');
    var a = arr.slice();
    for (var i = a.length - 1; i > 0; i--) {
      var j = randomInt(i + 1), t = a[i];
      a[i] = a[j]; a[j] = t;
    }
    return a;
  }

