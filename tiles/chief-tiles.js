  function checkPath(d, w, capH, at, fail) {
    if (typeof d !== 'string' || !d.trim()) fail(at + ' must be a non-empty string');
    var toks = [], m;
    PATH_TOKEN_RE.lastIndex = 0;
    while ((m = PATH_TOKEN_RE.exec(d))) {
      if (m[1]) toks.push(m[1]);
      else if (m[2]) toks.push(+m[2]);
      else if (m[4]) fail(at + ': invalid character ' + JSON.stringify(m[4]));
    }
    if (toks[0] !== 'M') fail(at + ' must start with M');
    var box = function (c, x, y) {
      if ((x !== null && (x < -1 || x > w + 1)) || (y !== null && (y < -1 || y > capH + 1))) {
        fail(at + ': ' + c + ' coordinate (' + (x === null ? '-' : x) + ', ' + (y === null ? '-' : y) +
          ') outside the glyph box x -1..' + (w + 1) + ', y -1..' + (capH + 1));
      }
    };
    var i = 0;
    while (i < toks.length) {
      var c = toks[i++];
      if (typeof c !== 'string' || !hasOwn(PATH_ARGS, c)) {
        fail(at + ': command ' + JSON.stringify(c) + ' not allowed (only absolute M L H V Q A Z)');
      }
      var args = [];
      while (i < toks.length && typeof toks[i] === 'number') args.push(toks[i++]);
      var na = PATH_ARGS[c];
      if (na === 0 ? args.length : (!args.length || args.length % na)) {
        fail(at + ': ' + c + ' takes ' + (na ? na + ' numbers per segment' : 'no numbers') + ', got ' + args.length);
      }
      for (var j = 0; na && j < args.length; j += na) {
        var a = args.slice(j, j + na);
        if (c === 'M' || c === 'L') box(c, a[0], a[1]);
        else if (c === 'H') box(c, a[0], null);
        else if (c === 'V') box(c, null, a[0]);
        else if (c === 'Q') { box(c, a[0], a[1]); box(c, a[2], a[3]); }
        else {
          if (!(a[0] > 0 && a[1] > 0)) fail(at + ': A radii must be > 0');
          if ((a[3] !== 0 && a[3] !== 1) || (a[4] !== 0 && a[4] !== 1)) fail(at + ': A flags must be 0 or 1');
          box(c, a[5], a[6]);
        }
      }
    }
  }

  /* full validation → normalized glyph font; throws Error('ChiefTiles glyphs "<id>": <path> …') */
  function validateGlyphs(input) {
    var s = input, id = '?', k;
    if (typeof input === 'string') {
      try { s = JSON.parse(input); } catch (e) { throw glyphErr(id, 'invalid JSON (' + e.message + ')'); }
    }
    if (!isObj(s)) throw glyphErr(id, 'glyphs must be a JSON object');
    if (typeof s.id !== 'string' || !ID_RE.test(s.id)) throw glyphErr(id, '"id" must be 1-40 chars [a-z0-9_-]');
    id = s.id;
    var fail = function (msg) { throw glyphErr(id, msg); };
    for (k in s) if (GLYPH_KEYS.indexOf(k) < 0) fail('unknown key "' + k + '" (allowed: ' + GLYPH_KEYS.join(', ') + ')');
    if (!isNum(s.capHeight) || s.capHeight <= 0 || s.capHeight > 100) fail('"capHeight" must be a number > 0');
    if (!isObj(s.glyphs)) fail('"glyphs" must be an object {"A": {w, d}, …}');
    var out = {};
    for (k in s.glyphs) {
      var g = s.glyphs[k], at = 'glyphs.' + k;
      if (k.length !== 1 || REQUIRED_GLYPHS.indexOf(k) < 0) fail('unknown glyph ' + JSON.stringify(k) + ' (allowed: A-Z, 0-9)');
      if (!isObj(g)) fail(at + ' must be an object {w, d}');
      for (var f in g) if (GLYPH_FIELDS.indexOf(f) < 0) fail(at + ': unknown key "' + f + '" (allowed: w, d)');
      if (!isNum(g.w) || g.w < 0 || g.w > 40) fail(at + '.w must be a number 0-40');
      checkPath(g.d, g.w, s.capHeight, at + '.d', fail);
      out[k] = { w: g.w, d: g.d };
    }
    for (var i = 0; i < REQUIRED_GLYPHS.length; i++) {
      if (!hasOwn(out, REQUIRED_GLYPHS[i])) fail('missing glyph "' + REQUIRED_GLYPHS[i] + '" (needs A-Z and 0-9)');
    }
    return { id: id, capHeight: s.capHeight, glyphs: out };
  }

