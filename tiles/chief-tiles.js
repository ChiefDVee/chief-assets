/* chief-tiles.js — ChiefTiles PoC: self-rendered letter tiles as SVG strings.
   Classic script (no ES modules, works via file://) → window.ChiefTiles (and module.exports under node).
   Colours, fonts: only var(--chief-*) → load brand/chief-tokens.css in the page. Zero external requests.
   Letter sets are config (JSON in sets/), inlined below by chief_tiles_inline_engine.py.
   Separate library from chief-cards.js: same patterns, no shared code. */
(function (root) {
  'use strict';

  var VERSION = '0.1.0';
  var W = 100, H = 100, CX = 50, CY = 50;              // viewBox (square tile)

  var FACE_STYLES = ['minimal', 'classic'];
  /* Defaults. radius = px at the rendered size; 8 mirrors --chief-radius-sm (an SVG rx attribute cannot read a CSS var). */
  var DEFAULTS = { size: 64, radius: 8, faceStyle: 'minimal', faceDown: false };
  var TOKEN_KEYS = ['faceToken', 'edgeToken', 'letterToken', 'valueToken'];

  /* Colours per faceStyle. minimal = flat dark tile in the house style; classic = cream tile with a darker base. */
  var STYLE_TOKENS = {
    minimal: { face: '--chief-surface-2', edge: '--chief-border-strong', letter: '--chief-text', value: '--chief-accent',
      blank: '--chief-accent', back: '--chief-surface', backMark: '--chief-accent', backRule: '--chief-accent-dim', base: null },
    classic: { face: '--chief-die', edge: '--chief-print-rule', letter: '--chief-bg', value: '--chief-bg',
      blank: '--chief-print-muted', back: '--chief-die', backMark: '--chief-print-muted', backRule: '--chief-print-rule',
      base: '--chief-print-muted' }
  };

  /* Letter fit: font size per letter length (code points), then an estimated width per glyph (em fraction).
     Wider than MAX_LETTER_W → textLength squeezes it (only shrinks, never stretches). */
  var LETTER_FONT = { 1: 60, 2: 40, 3: 30 };
  var MAX_LETTER_W = 70;
  var GLYPH_W = { I: 0.28, J: 0.52, L: 0.56, F: 0.58, E: 0.6, T: 0.6, M: 0.84, W: 0.92 };
  var CAP = 0.72;                                      // cap height ≈ 0.72 em (system sans)

  /* ================= BUILTIN_SETS (file:// cannot fetch JSON) ================= */
  /* BUILTIN_SETS:START — GENERATED by chief_tiles_inline_engine.py from sets/*.json — do not edit by hand */
  var BUILTIN_SETS = {
    "demo": {
      "id": "demo",
      "name": "DEMO — placeholder values, not a real distribution",
      "lang": "nl",
      "tiles": [
        {"letter": "A", "value": 1, "count": 2},
        {"letter": "E", "value": 1, "count": 2},
        {"letter": "N", "value": 1, "count": 2},
        {"letter": "O", "value": 1, "count": 2},
        {"letter": "I", "value": 2, "count": 2},
        {"letter": "D", "value": 2, "count": 2},
        {"letter": "T", "value": 2, "count": 2},
        {"letter": "K", "value": 3, "count": 2},
        {"letter": "W", "value": 5, "count": 2},
        {"letter": "IJ", "value": 4, "count": 2},
        {"letter": "Z", "value": 10, "count": 2}
      ],
      "blanks": 2
    }
  };
  /* BUILTIN_SETS:END */

  /* ---------------------------------- helpers ---------------------------------- */
  var CHIEF_TOKEN_RE = /^--chief-[a-z0-9-]+$/;   // opts + tile meta: house-style tokens only
  var ID_RE = /^[a-z0-9_-]{1,40}$/;
  var LANG_RE = /^[a-z]{2,3}$/;
  var MAX = { letter: 3, value: 99, count: 100, blanks: 20, name: 60 };
  var hasOwn = function (o, k) { return Object.prototype.hasOwnProperty.call(o, k); };

  function n(x) { return Math.round(x * 100) / 100; }
  /* XML escape for text + attribute values. Tile data (letter, id) is always RAW text; render() escapes it exactly
     once here. "&amp;" in the data is literal text and renders as "&amp;amp;". Only used inside render(). */
  function esc(s) {
    return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&apos;');
  }
  function chars(s) { return Array.from ? Array.from(String(s)) : String(s).split(''); }
  function isObj(o) { return !!o && typeof o === 'object' && !Array.isArray(o); }
  function isInt(v) { return typeof v === 'number' && isFinite(v) && v % 1 === 0; }
  function fill(t) { return 'fill:var(' + t + ')'; }
  function stroke(t, w) { return 'fill:none;stroke:var(' + t + ');stroke-width:' + w; }
  function font(size, weight) {
    return 'font-family:var(--chief-font-body);font-weight:' + (weight || 700) + ';font-size:' + size + 'px';
  }

  /* estimated rendered width of a letter at font size fs */
  function letterWidth(letter, fs) {
    var cs = chars(letter), w = 0;
    for (var i = 0; i < cs.length; i++) {
      var c = cs[i].toUpperCase();
      w += (hasOwn(GLYPH_W, c) ? GLYPH_W[c] : 0.68) * fs;
    }
    return w;
  }
  /* → {fs, y, fit}: font size, baseline (cap height centred on CY), textLength attribute or '' */
  function letterFit(letter) {
    var len = chars(letter).length;
    var fs = LETTER_FONT[Math.min(len, 3)];
    var fit = letterWidth(letter, fs) > MAX_LETTER_W ? ' textLength="' + MAX_LETTER_W + '" lengthAdjust="spacingAndGlyphs"' : '';
    return { fs: fs, y: n(CY + CAP * fs / 2), fit: fit };
  }

  /* ---------------------------------- validation ---------------------------------- */
  function tokenErr(where, k, v) {
    return new Error('ChiefTiles: ' + where + '.' + k + ' = ' + JSON.stringify(v) + ' is not a valid token (must start with "--chief-")');
  }
  function checkTokens(obj, where) {
    var out = {};
    if (!obj) return out;
    for (var i = 0; i < TOKEN_KEYS.length; i++) {
      var k = TOKEN_KEYS[i];
      if (obj[k] === undefined || obj[k] === null) continue;
      if (typeof obj[k] !== 'string' || !CHIEF_TOKEN_RE.test(obj[k])) throw tokenErr(where, k, obj[k]);
      out[k] = obj[k];
    }
    return out;
  }
  function checkLetter(v, at, fail, allowEmpty) {
    if (typeof v !== 'string') fail(at + ' must be a string');
    var len = chars(v).length;
    if (!len && allowEmpty) return;
    if (!len || len > MAX.letter || !v.trim() || v.trim() !== v) fail(at + ' must be 1-' + MAX.letter + ' characters without surrounding spaces');
  }

  function normalizeOpts(opts) {
    var o = {}, k;
    for (k in DEFAULTS) o[k] = DEFAULTS[k];
    if (opts) for (k in opts) if (opts[k] !== undefined && opts[k] !== null) o[k] = opts[k];
    o.size = +o.size; o.radius = +o.radius;
    if (!(o.size > 0)) throw new Error('ChiefTiles.render: opts.size must be a positive number');
    if (!(o.radius >= 0)) throw new Error('ChiefTiles.render: opts.radius must be >= 0');
    if (FACE_STYLES.indexOf(o.faceStyle) < 0) throw new Error('ChiefTiles.render: opts.faceStyle must be one of ' + FACE_STYLES.join(', '));
    o.faceDown = !!o.faceDown;
    o.tokens = checkTokens(opts, 'opts');
    return o;
  }

  function checkTile(tile) {
    var fail = function (msg) { throw new Error('ChiefTiles.render: ' + msg); };
    if (!isObj(tile)) fail('tile must be an object {id?, letter, value, blank?}');
    if (tile.blank) {
      if (tile.letter !== undefined && tile.letter !== null) checkLetter(tile.letter, 'tile.letter', fail, true);
    } else {
      checkLetter(tile.letter, 'tile.letter', fail, false);
      if (!isInt(tile.value) || tile.value < 0) fail('tile.value must be an integer >= 0');
    }
    if (tile.meta !== undefined && !isObj(tile.meta)) fail('tile.meta must be an object');
    return checkTokens(tile.meta, 'tile.meta');
  }

  /* ---------------------------------- render ---------------------------------- */
  function body(rx, faceTok, edgeTok, baseTok) {
    var out = '';
    if (baseTok) {                                   // classic: darker base peeking out at the bottom (tile thickness)
      out += '<rect x="1" y="5" width="' + (W - 2) + '" height="' + (H - 6) + '" rx="' + n(rx) + '" ry="' + n(rx) + '" style="' + fill(baseTok) + '"/>';
      return out + '<rect x="1" y="1" width="' + (W - 2) + '" height="' + (H - 6) + '" rx="' + n(rx) + '" ry="' + n(rx) + '" style="' +
        fill(faceTok) + ';stroke:var(' + edgeTok + ');stroke-width:1.5"/>';
    }
    return out + '<rect x="1" y="1" width="' + (W - 2) + '" height="' + (H - 2) + '" rx="' + n(rx) + '" ry="' + n(rx) + '" style="' +
      fill(faceTok) + ';stroke:var(' + edgeTok + ');stroke-width:2"/>';
  }

  function backFace(st, rx, tk) {
    var face = tk.faceToken || st.back, edge = tk.edgeToken || st.edge;
    var inset = n(Math.max(rx - 6, 2));
    var cy = st.base ? CY - 2 : CY;
    return body(rx, face, edge, st.base) +
      '<rect x="12" y="' + (st.base ? 10 : 12) + '" width="76" height="' + (st.base ? 72 : 76) + '" rx="' + inset + '" style="' + stroke(st.backRule, 2) + '"/>' +
      '<path d="M50,' + n(cy - 14) + ' L64,' + n(cy) + ' L50,' + n(cy + 14) + ' L36,' + n(cy) + ' Z" style="' + fill(st.backMark) + '"/>';
  }

  function tileLabel(tile) {
    if (tile.blank) return tile.letter ? 'Blank tile as ' + tile.letter : 'Blank tile';
    return 'Letter tile ' + tile.letter + ', ' + tile.value + (tile.value === 1 ? ' point' : ' points');
  }

  function render(tile, opts) {
    var metaTok = checkTile(tile);
    var o = normalizeOpts(opts);
    var tk = {}, k;
    for (k in o.tokens) tk[k] = o.tokens[k];
    for (k in metaTok) tk[k] = metaTok[k];         // tile meta wins over opts
    var st = STYLE_TOKENS[o.faceStyle];
    var rx = Math.min(o.radius * W / o.size, 40);
    var inner, aria, cyShift = st.base ? -2 : 0;

    if (o.faceDown) {
      inner = backFace(st, rx, tk);
      aria = 'Tile, face down';
    } else {
      inner = body(rx, tk.faceToken || st.face, tk.edgeToken || st.edge, st.base);
      aria = tileLabel(tile);
      var letter = tile.letter ? String(tile.letter) : '';
      if (tile.blank) {
        inner += '<rect x="9" y="' + (9 + cyShift) + '" width="82" height="82" rx="' + n(Math.max(rx - 5, 2)) + '" style="' +
          stroke(tk.edgeToken || st.blank, 2) + ';stroke-dasharray:6,4"/>';
      }
      if (letter) {
        var f = letterFit(letter);
        var lt = tk.letterToken || (tile.blank ? st.blank : st.letter);
        inner += '<text x="' + CX + '" y="' + n(f.y + cyShift) + '" text-anchor="middle"' + f.fit + ' style="' + fill(lt) + ';' +
          font(f.fs, tile.blank ? 600 : 800) + (tile.blank ? ';font-style:italic' : '') + '">' + esc(letter) + '</text>';
      }
      if (!tile.blank) {
        inner += '<text x="89" y="' + (89 + cyShift) + '" text-anchor="end" style="' + fill(tk.valueToken || st.value) + ';' +
          font(String(tile.value).length > 1 ? 15 : 18, 700) + '">' + esc(tile.value) + '</text>';
      }
    }
    return '<svg xmlns="http://www.w3.org/2000/svg" class="ct-svg" viewBox="0 0 ' + W + ' ' + H + '" width="' + n(o.size) +
      '" height="' + n(o.size * H / W) + '" role="img" aria-label="' + esc(aria) + '"' +
      (!o.faceDown && tile.id !== undefined && tile.id !== null ? ' data-tile-id="' + esc(tile.id) + '"' : '') + '>' + inner + '</svg>';
  }

  /* ---------------------------------- sets ---------------------------------- */
  var SET_KEYS = ['id', 'name', 'lang', 'tiles', 'blanks'];
  var TILE_KEYS = ['letter', 'value', 'count'];

  function setErr(id, msg) { return new Error('ChiefTiles set "' + id + '": ' + msg); }

  /* full validation → normalized set; throws Error('ChiefTiles set "<id>": <path> …') */
  function validateSet(input) {
    var s = input, id = '?', i, k;
    if (typeof input === 'string') {
      try { s = JSON.parse(input); } catch (e) { throw setErr(id, 'invalid JSON (' + e.message + ')'); }
    }
    if (!isObj(s)) throw setErr(id, 'set must be a JSON object');
    if (typeof s.id !== 'string' || !ID_RE.test(s.id)) throw setErr(id, '"id" must be 1-40 chars [a-z0-9_-]');
    id = s.id;
    var fail = function (msg) { throw setErr(id, msg); };
    for (k in s) if (SET_KEYS.indexOf(k) < 0) fail('unknown key "' + k + '" (allowed: ' + SET_KEYS.join(', ') + ')');
    if (typeof s.name !== 'string' || !s.name.trim() || chars(s.name).length > MAX.name) fail('"name" must be a non-empty string (max ' + MAX.name + ' chars)');
    if (typeof s.lang !== 'string' || !LANG_RE.test(s.lang)) fail('"lang" must be a 2-3 letter language code in lower case (nl, en, …)');
    if (!Array.isArray(s.tiles) || !s.tiles.length) fail('"tiles" must be a non-empty array');
    var blanks = s.blanks === undefined ? 0 : s.blanks;
    if (!isInt(blanks) || blanks < 0 || blanks > MAX.blanks) fail('"blanks" must be an integer 0-' + MAX.blanks);
    var tiles = [], seen = {}, total = blanks;
    for (i = 0; i < s.tiles.length; i++) {
      var t = s.tiles[i], at = 'tiles[' + i + ']';
      if (!isObj(t)) fail(at + ' must be an object {letter, value, count}');
      for (k in t) if (TILE_KEYS.indexOf(k) < 0) fail(at + ': unknown key "' + k + '" (allowed: ' + TILE_KEYS.join(', ') + ')');
      TILE_KEYS.forEach(function (f) { if (t[f] === undefined) fail(at + ': missing field "' + f + '"'); });
      checkLetter(t.letter, at + '.letter', fail, false);
      var key = t.letter.toUpperCase();
      if (hasOwn(seen, key)) fail(at + '.letter = ' + JSON.stringify(t.letter) + ' is a duplicate (also ' + seen[key] + ')');
      seen[key] = at;
      if (!isInt(t.value) || t.value < 0 || t.value > MAX.value) fail(at + '.value must be an integer 0-' + MAX.value);
      if (!isInt(t.count) || t.count < 1 || t.count > MAX.count) fail(at + '.count must be an integer 1-' + MAX.count);
      tiles.push({ letter: t.letter, value: t.value, count: t.count });
      total += t.count;
    }
    return { id: id, name: s.name, lang: s.lang, tiles: tiles, blanks: blanks, total: total };
  }

  /* id-safe slug of a letter: [a-z0-9] as is (lower case), anything else u<hex code point> */
  function letterSlug(letter) {
    var cs = chars(letter.toLowerCase()), out = '';
    for (var i = 0; i < cs.length; i++) out += /^[a-z0-9]$/.test(cs[i]) ? cs[i] : 'u' + cs[i].codePointAt(0).toString(16);
    return out;
  }

  /* input = set JSON (object/string) or a BUILTIN_SETS id → flat array of tiles
     {id: <set>-<letter>-<n>, letter, value} + blanks {id: <set>-blank-<n>, letter: '', value: 0, blank: true} */
  function loadSet(input) {
    var src = (typeof input === 'string' && hasOwn(BUILTIN_SETS, input)) ? BUILTIN_SETS[input] : input;
    var v = validateSet(src), out = [], seen = {}, i, c;
    for (i = 0; i < v.tiles.length; i++) {
      var t = v.tiles[i];
      for (c = 1; c <= t.count; c++) out.push({ id: v.id + '-' + letterSlug(t.letter) + '-' + c, letter: t.letter, value: t.value });
    }
    for (c = 1; c <= v.blanks; c++) out.push({ id: v.id + '-blank-' + c, letter: '', value: 0, blank: true });
    for (i = 0; i < out.length; i++) {
      if (seen[out[i].id]) throw setErr(v.id, 'duplicate tile id "' + out[i].id + '"');
      seen[out[i].id] = true;
    }
    return out;
  }

  /* ------------------------- mount: CSP-safe DOM insert ------------------------- */
  /* Same approach as ChiefCards: render() colours via style="fill:var(--chief-…)". Under a strict CSP (style-src without
     'unsafe-inline') style attributes in markup are blocked, and DOMParser also reports a violation. splitStyles() is the
     pure step: every style="…" becomes data-ct-s="<index>" and the declarations go to a list. render() escapes " in text
     as &quot;, so the pattern only ever matches attributes. Joining them back gives render()'s string byte for byte. */
  var STYLE_ATTR_RE = / style="([^"]*)"/g, STASH_ATTR = 'data-ct-s';
  function splitStyles(svg) {
    if (typeof svg !== 'string' || svg.indexOf('<svg') !== 0) throw new Error('ChiefTiles.splitStyles: expects an SVG string from render()');
    var styles = [];
    var markup = svg.replace(STYLE_ATTR_RE, function (_m, css) {
      styles.push(css);
      return ' ' + STASH_ATTR + '="' + (styles.length - 1) + '"';
    });
    return { markup: markup, styles: styles };
  }
  function applyDecls(el, css) {
    var parts = String(css).split(';');
    for (var i = 0; i < parts.length; i++) {
      var k = parts[i].indexOf(':');
      if (k > 0) el.style.setProperty(parts[i].slice(0, k).trim(), parts[i].slice(k + 1).trim());
    }
  }
  /* mount(el, svg): replaces the children of el with the SVG (DOMParser + importNode, never innerHTML); styles go via
     CSSOM (el.style.setProperty), which a CSP does not block. Returns the inserted <svg> element. */
  function mount(el, svg) {
    if (!el || el.nodeType !== 1) throw new Error('ChiefTiles.mount: el must be a DOM element');
    var parts = splitStyles(svg);
    var doc = el.ownerDocument;
    var Parser = (doc.defaultView && doc.defaultView.DOMParser) || root.DOMParser;
    var parsed = new Parser().parseFromString(parts.markup, 'image/svg+xml').documentElement;
    if (!parsed || parsed.nodeName.toLowerCase() !== 'svg' || parsed.getElementsByTagName('parsererror').length) {
      throw new Error('ChiefTiles.mount: markup is not a valid SVG');
    }
    var node = doc.importNode(parsed, true);
    var marked = [node].concat(Array.prototype.slice.call(node.querySelectorAll('[' + STASH_ATTR + ']')));
    for (var i = 0; i < marked.length; i++) {
      if (!marked[i].hasAttribute(STASH_ATTR)) continue;
      var idx = +marked[i].getAttribute(STASH_ATTR);
      marked[i].removeAttribute(STASH_ATTR);
      if (idx >= 0 && idx < parts.styles.length) applyDecls(marked[i], parts.styles[idx]);
    }
    while (el.firstChild) el.removeChild(el.firstChild);
    el.appendChild(node);
    return node;
  }

  var api = {
    VERSION: VERSION, DEFAULTS: DEFAULTS, FACE_STYLES: FACE_STYLES, TOKEN_KEYS: TOKEN_KEYS, BUILTIN_SETS: BUILTIN_SETS,
    render: render, splitStyles: splitStyles, mount: mount, validateSet: validateSet, loadSet: loadSet
  };
  root.ChiefTiles = api;
  if (typeof module === 'object' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
